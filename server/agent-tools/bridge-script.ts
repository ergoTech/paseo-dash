/**
 * The stdio MCP server a task agent runs as its "dashboard" tools (05-architecture.md, The agent's own
 * report). It is written to plugin-data at start and run by the plugin worker's own binary, so it
 * needs nothing on PATH (08-phase-3-spikes.md, spike A). It holds no state: each tool call goes to
 * the plugin over its Unix socket with the run's token, and a plugin that is reloading answers
 * "not reachable" instead of hanging the agent.
 */

import { draftSchema, findSchema, reportSchema, taskSchema, toolInputSchema } from "./schema.ts";

export const TOOLS = [
  {
    name: "task_brief",
    description:
      "Read your Paseo Dash task again as it stands now: brief, acceptance lines with what is ticked, dependencies, links and the latest handoff. Use it after your context was compacted.",
    inputSchema: { type: "object", properties: {}, additionalProperties: false },
  },
  {
    name: "task_report",
    description:
      'Report progress on your Paseo Dash task. "done": acceptance lines you finished, by their text or number. "state": working, blocked (with "blocker") or done when the whole task is complete. "pr_url": the merge request once it is open. "handoff": what the next agent on this task needs; send it before state done or blocked and before you stop.',
    inputSchema: toolInputSchema(reportSchema),
  },
];

/**
 * The plan tools (server/agent-tools/plan.ts): any agent whose repository is a project of a connected
 * space, while the switch in Settings is on. Reading and adding Inbox drafts only.
 */
export const PLAN_TOOLS = [
  {
    name: "plan_find",
    description: "Search this repo's Paseo Dash plan by words, e.g. for duplicates. Lines: ID status title.",
    inputSchema: toolInputSchema(findSchema),
  },
  {
    name: "plan_task",
    description: "Read a plan task: status, brief, acceptance.",
    inputSchema: toolInputSchema(taskSchema),
  },
  {
    name: "plan_add_draft",
    description: "Add a draft task for this repo to the plan's Inbox. Run plan_find first.",
    inputSchema: toolInputSchema(draftSchema),
  },
];

/** The script's source: plain JavaScript for the Node inside Paseo (no imports beyond node:). */
export function bridgeScript(): string {
  return `// Generated by the Paseo dashboard plugin; rewritten at every plugin start. Do not edit.
import { createConnection } from "node:net";
import { createInterface } from "node:readline";

const SOCKET = process.env.DASHBOARD_SOCKET ?? "";
const TOKEN = process.env.DASHBOARD_TOKEN ?? "";
// One script, two servers: a run's task tools, or the plan tools of any agent.
const TOOLS = process.env.DASHBOARD_TOOLS === "plan" ? ${JSON.stringify(PLAN_TOOLS)} : ${JSON.stringify(TOOLS)};
const UNREACHABLE = "Paseo Dash is not reachable right now (the plugin may be reloading). Carry on with the work and report again later.";

function call(tool, args) {
  return new Promise((resolve) => {
    let buffer = "";
    let settled = false;
    const finish = (answer) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      socket.destroy();
      resolve(answer);
    };
    const socket = createConnection(SOCKET);
    // Whole characters across chunk boundaries: briefs are often Cyrillic.
    socket.setEncoding("utf8");
    const timer = setTimeout(() => finish({ ok: false, text: UNREACHABLE }), 15000);
    socket.on("connect", () => socket.write(JSON.stringify({ token: TOKEN, tool, args }) + "\\n"));
    socket.on("data", (chunk) => {
      buffer += chunk;
      const end = buffer.indexOf("\\n");
      if (end < 0) return;
      try {
        finish(JSON.parse(buffer.slice(0, end)));
      } catch {
        finish({ ok: false, text: UNREACHABLE });
      }
    });
    socket.on("error", () => finish({ ok: false, text: UNREACHABLE }));
    socket.on("close", () => finish({ ok: false, text: UNREACHABLE }));
  });
}

const send = (message) => process.stdout.write(JSON.stringify(message) + "\\n");

createInterface({ input: process.stdin }).on("line", async (line) => {
  if (!line.trim()) return;
  let message;
  try {
    message = JSON.parse(line);
  } catch {
    return;
  }
  if (message.id === undefined || message.id === null) return;
  const reply = (result) => send({ jsonrpc: "2.0", id: message.id, result });
  switch (message.method) {
    case "initialize":
      return reply({
        protocolVersion: message.params?.protocolVersion ?? "2025-06-18",
        capabilities: { tools: {} },
        serverInfo: { name: process.env.DASHBOARD_TOOLS === "plan" ? "dashboard_plan" : "dashboard", version: "1" },
      });
    case "ping":
      return reply({});
    case "tools/list":
      return reply({ tools: TOOLS });
    case "tools/call": {
      const answer = await call(String(message.params?.name ?? ""), message.params?.arguments ?? {});
      return reply({ content: [{ type: "text", text: String(answer.text ?? "") }], isError: !answer.ok });
    }
    default:
      return send({ jsonrpc: "2.0", id: message.id, error: { code: -32601, message: "Method not found" } });
  }
});
`;
}
