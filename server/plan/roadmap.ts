import type { Glyph } from "../../shared/map.ts";
import { type Milestone, refId, type Task } from "../../shared/model.ts";
import { blockingTasks, featuresOf, milestoneOf, milestonesOf, tasksOf } from "../api/view.ts";
import { planGlyph } from "../map/metro.ts";
import type { Plan } from "./load.ts";

/**
 * `ROADMAP.md` for people without Paseo (04-ux.md, For people without Paseo; 05-architecture.md,
 * Derived files): per open release a feature × project table with the metro's marks (and the labels
 * of each row's tasks, when any task there has one) and a Mermaid
 * flowchart per feature, then a Mermaid gantt of the releases with dates (two or more). A pure
 * function of the committed plan: no clock, no runtime state, everything in a fixed order, so every
 * machine renders the same text for the same plan.
 */

export const ROADMAP_FILE = "ROADMAP.md";

const HEADER = "<!-- Generated by the Paseo dashboard plugin from the plan files. Do not edit it by hand: it is rewritten with the next change. -->";

const MARK: Partial<Record<Glyph, string>> = { done: "✓", review: "◇", elsewhere: "◐", todo: "○", blocked: "⊘" };
const LEGEND = "✓ done · ◇ in review · ◐ in progress · ○ to do · ⊘ waits for another task · · no task in this project";

/**
 * Text other people wrote, safe in Markdown prose and table cells: no HTML, cell breaks, emphasis,
 * link or math markup, and no Obsidian comments or highlights. A bare URL may still show as a link.
 */
export function mdText(text: string): string {
  return text
    .replace(/[\r\n]+/g, " ")
    .replace(/([\\`*_[\]<>|#~!$%=])/g, "\\$1")
    .trim();
}

/** Plain code point order: the same on every machine, whatever the daemon's locale. */
function byText(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** The YYYY-MM-DD day a value starts with, when it is a real calendar day; else "". */
function realDay(value: string | undefined): string {
  const day = /^\d{4}-\d{2}-\d{2}/.exec(value ?? "")?.[0] ?? "";
  const parsed = new Date(`${day}T00:00:00Z`);
  return day && !Number.isNaN(parsed.getTime()) && parsed.toISOString().slice(0, 10) === day ? day : "";
}

/** Text in a quoted Mermaid label: entity codes for what Mermaid or its HTML labels would read. */
export function mermaidLabel(text: string): string {
  return text
    .replace(/[\r\n]+/g, " ")
    .replace(/#/g, "#35;")
    // "%%{init: …}%%" anywhere in the diagram text is read as a directive.
    .replace(/%/g, "#37;")
    .replace(/"/g, "#quot;")
    .replace(/</g, "#lt;")
    .replace(/>/g, "#gt;")
    .replace(/`/g, "#96;")
    .trim();
}

/**
 * A gantt task name: the syntax splits on ":" and ";" and starts comments with "%%", so those go; a
 * fixed lead keeps a name such as "Title page" or "2026-12-01 hotfix" from reading as a keyword or date.
 */
function ganttName(text: string): string {
  return `▸ ${text.replace(/[\r\n:;#%]+/g, " ").replace(/\s+/g, " ").trim() || "(untitled)"}`;
}

/** "#12" for a GitHub pull request, "!410" for a GitLab merge request, else nothing. */
function prLabel(url: string | undefined): string {
  const match = url ? /\/(pull|merge_requests)\/(\d+)\/?$/.exec(url) : null;
  return match ? `${match[1] === "pull" ? "#" : "!"}${match[2]}` : "";
}

const finished = (m: Milestone) => m.status === "done" || m.status === "canceled";
const byDue = (a: Milestone, b: Milestone) =>
  byText(realDay(a.due) || "9999", realDay(b.due) || "9999") || (a.order ?? 0) - (b.order ?? 0) || byText(a.id, b.id);

function statusText(plan: Plan, task: Task): string {
  switch (task.status) {
    case "done":
      return "done";
    case "review":
      return ["review", prLabel(task.run_pr)].filter(Boolean).join(" ");
    case "in_progress":
      return ["in progress", task.progress_total ? `${task.progress_done ?? 0}/${task.progress_total}` : ""].filter(Boolean).join(" ");
    default: {
      const waits = blockingTasks(plan, task).map((b) => b.id);
      return waits.length ? `waits for ${waits.join(", ")}` : "to do";
    }
  }
}

const CLASS: Record<string, string> = { done: "done", review: "review", elsewhere: "progress", blocked: "blocked", todo: "todo" };
const CLASS_DEFS = [
  "classDef done fill:#d4f5dd,stroke:#2f8f4e,color:#111",
  "classDef review fill:#dde8ff,stroke:#3b63c4,color:#111",
  "classDef progress fill:#fff1cc,stroke:#b7860b,color:#111",
  "classDef blocked fill:#f3f3f3,stroke:#999999,color:#111",
  "classDef todo fill:#ffffff,stroke:#999999,stroke-dasharray:4 3,color:#111",
];

export function renderRoadmap(plan: Plan): string | undefined {
  if (!plan.space) return undefined;
  const space = plan.space;
  const known = Object.keys(space.projects);
  const projectOrder = (project: string) => {
    const index = known.indexOf(project);
    return index === -1 ? known.length : index;
  };
  const sortProjects = (projects: string[]) => [...new Set(projects)].sort((a, b) => projectOrder(a) - projectOrder(b) || byText(a, b));

  const milestones = milestonesOf(plan);
  const open = milestones.filter((m) => !finished(m)).sort(byDue);
  const openIds = new Set(open.map((m) => m.id));
  const features = new Map(featuresOf(plan).map((f) => [f.id, f]));
  const tasks = tasksOf(plan)
    .filter((t) => t.status !== "canceled" && t.status !== "inbox")
    .sort((a, b) => projectOrder(a.project ?? "") - projectOrder(b.project ?? "") || byText(a.id, b.id));
  // A task's release is its own, else its feature's; open work of a finished release counts as later.
  const releaseOf = (task: Task) => {
    const id = milestoneOf(plan, task);
    return id && openIds.has(id) ? id : "";
  };

  const out: string[] = [HEADER, "", `# ${mdText(space.name)} roadmap`, "", `Legend: ${LEGEND}`, ""];
  const sections = [...open.map((m) => ({ id: m.id, milestone: m as Milestone | undefined })), { id: "", milestone: undefined as Milestone | undefined }];
  for (const { id, milestone } of sections) {
    const own = tasks.filter((t) => releaseOf(t) === id && (id !== "" || t.status !== "done"));
    if (!milestone && own.length === 0) continue;
    const done = own.filter((t) => t.status === "done").length;
    const head = milestone
      ? [mdText(milestone.title), realDay(milestone.due) ? `due ${realDay(milestone.due)}` : "", `${done}/${own.length} done`]
      : ["Later", `${own.length} open`];
    out.push(`## ${head.filter(Boolean).join(" · ")}`, "");
    if (own.length === 0) {
      out.push("No tasks yet.", "");
      continue;
    }
    const projects = sortProjects(own.map((t) => t.project ?? "?"));
    const featureOf = (t: Task) => {
      const f = features.get(refId(t.feature) ?? "");
      return f && f.status !== "canceled" ? f.id : "";
    };
    const rowIds = [...new Set(own.map(featureOf))].sort((a, b) => {
      if (!a || !b) return a ? -1 : b ? 1 : 0;
      const fa = features.get(a)!;
      const fb = features.get(b)!;
      return (fa.order ?? 0) - (fb.order ?? 0) || byText(a, b);
    });
    // Labels in palette order, then the ones it does not define by name; each as the palette spells it.
    const palette = Object.keys(space.labels);
    const rank = (label: string) => {
      const index = palette.findIndex((name) => name.toLowerCase() === label.toLowerCase());
      return index === -1 ? palette.length : index;
    };
    const labelsOf = (tasks: Task[]) => {
      const seen = new Map<string, string>();
      for (const t of tasks) for (const label of t.labels) if (!seen.has(label.toLowerCase())) seen.set(label.toLowerCase(), palette.find((name) => name.toLowerCase() === label.toLowerCase()) ?? label);
      return [...seen.values()].sort((a, b) => rank(a) - rank(b) || byText(a, b));
    };
    const labelled = own.some((t) => t.labels.length > 0);
    const extra = labelled ? ["Labels"] : [];
    out.push(`| Feature | ${[...extra, ...projects.map(mdText)].join(" | ")} |`, `| --- | ${[...extra.map(() => "---"), ...projects.map(() => ":-:")].join(" | ")} |`);
    for (const row of rowIds) {
      const feature = row ? features.get(row) : undefined;
      const name = feature ? `${mdText(feature.title)}${feature.branch ? ` · \`${feature.branch.replace(/[`|\r\n]/g, "")}\`` : ""}` : "Tasks without a feature";
      const cells = projects.map((project) => {
        const marks = own.filter((t) => featureOf(t) === row && (t.project ?? "?") === project).map((t) => planGlyph(plan, t));
        if (!marks.length) return "·";
        const order: Glyph[] = ["review", "elsewhere", "blocked", "todo", "done"];
        const worst = [...marks].sort((x, y) => order.indexOf(x) - order.indexOf(y))[0]!;
        return `${MARK[worst] ?? "○"}${marks.length > 1 ? ` ${marks.length}` : ""}`;
      });
      const labels = labelled ? [labelsOf(own.filter((t) => featureOf(t) === row)).map(mdText).join(", ") || "·"] : [];
      out.push(`| ${name} | ${[...labels, ...cells].join(" | ")} |`);
    }
    out.push("");
    for (const row of rowIds.filter(Boolean)) {
      const feature = features.get(row)!;
      const nodes = own.filter((t) => featureOf(t) === row);
      const ids = new Set(nodes.map((t) => t.id));
      const node = (t: Task) => `t_${t.id.replace(/-/g, "_")}`;
      out.push(`### ${mdText(feature.title)}`, "", "```mermaid", "flowchart LR");
      for (const def of CLASS_DEFS) out.push(`    ${def}`);
      for (const t of nodes) {
        const label = mermaidLabel(`${t.project ?? "?"} · ${t.title} · ${statusText(plan, t)}`);
        out.push(`    ${node(t)}["${label}"]:::${CLASS[planGlyph(plan, t)] ?? "todo"}`);
      }
      for (const t of nodes) {
        for (const ref of t.depends_on) {
          const dep = refId(ref);
          if (dep && ids.has(dep) && dep !== t.id) out.push(`    t_${dep.replace(/-/g, "_")} --> ${node(t)}`);
        }
      }
      out.push("```", "");
    }
  }

  const dated = milestones.filter((m) => m.status !== "canceled" && realDay(m.due)).sort(byDue);
  // One release on a time axis is a lone mark that says nothing its heading does not.
  if (dated.length >= 2) {
    out.push("## Releases over time", "", "```mermaid", "gantt", "    dateFormat YYYY-MM-DD", "    section Releases");
    dated.forEach((m, index) => {
      const due = realDay(m.due);
      const start = realDay(m.start) && realDay(m.start) < due ? realDay(m.start) : "";
      const tags = [m.status === "done" ? "done" : m.status === "active" ? "active" : "", start ? "" : "milestone"].filter(Boolean);
      const when = start ? `${start}, ${due}` : `${due}, 0d`;
      out.push(`    ${ganttName(m.title)} :${[...tags, `r${index}`].join(", ")}, ${when}`);
    });
    out.push("```", "");
  }
  const closed = milestones.filter(finished).sort(byDue);
  if (closed.length) {
    out.push("## Finished releases", "");
    for (const m of closed) out.push(`- ${mdText(m.title)} · ${m.status}${realDay(m.due) ? ` · ${realDay(m.due)}` : ""}`);
    out.push("");
  }
  return `${out.join("\n").trimEnd()}\n`;
}
