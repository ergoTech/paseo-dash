test("ROADMAP.md: a table per open release, a flowchart per feature and the releases over time", async () => {
  const s = await setup();
  try {
    await updateTask(s.ctx, { task: "TST-DEP01", feature: "TST-FEAT0" });
    const text = renderRoadmap(s.sync().plan)!;
    const lines = text.split("\n");
    assert.match(lines[0]!, /^<!-- Generated by the Paseo dashboard plugin/);
    for (const line of [
      "# Test space roadmap",
      "## Release 2.3 · due 2026-11-30 · 0/1 done",
      "| Feature | core |",
      "| Login · `feat/login` | ○ |",
      '    t_TST_FX001["core · Fix flaky login test · to do"]:::todo',
      "## Later · 5 open",
      "| Feature | core | site |",
      "| TOTP · `feat/totp` | ⊘ 3 | · |",
      "| Tasks without a feature | ◐ | ○ |",
      '    t_TST_DEP01["core · Blocked thing · waits for TST-TASK1"]:::blocked',
      "    t_TST_TASK1 --> t_TST_DEP01",
    ]) {
      assert.ok(lines.includes(line), `missing ${JSON.stringify(line)} in\n${text}`);
    }
    assert.doesNotMatch(text, /Releases over time|gantt/, "one dated release makes no time axis");
    await createMilestone(s.ctx, { title: "Release 2.4", due: "2026-12-21" });
    const two = renderRoadmap(s.sync().plan)!.split("\n");
    assert.ok(two.includes("## Releases over time"));
    assert.ok(two.includes("    ▸ Release 2.3 :active, milestone, r0, 2026-11-30, 0d"));
    assert.ok(two.includes("    ▸ Release 2.4 :milestone, r1, 2026-12-21, 0d"));
  } finally {
    s.stop();
  }
});

test("ROADMAP.md shows each row's labels in palette order once a task of the release has one", async () => {
  const s = await setup();
  try {
    const before = renderRoadmap(s.sync().plan)!;
    assert.ok(before.split("\n").includes("| Feature | core |"), "no labels: no Labels column");
    await createTask(s.ctx, { title: "Labelled", project: "core", labels: ["zeta", "alpha"] });
    await updateTask(s.ctx, { task: "TST-FX001", add_labels: ["a|b"] }).then((r) => assert.match(r.error, /not a usable label/));
    await updateTask(s.ctx, { task: "TST-TASK1", add_labels: ["alpha"] });
    const lines = renderRoadmap(s.sync().plan)!.split("\n");
    for (const line of [
      "| Feature | core |",
      "| Login · `feat/login` | ○ |",
      "| Feature | Labels | core | site |",
      "| --- | --- | :-: | :-: |",
      "| TOTP · `feat/totp` | alpha | ○ 2 | · |",
      // The palette got zeta first: it was typed first.
      "| Tasks without a feature | zeta, alpha | ◐ 3 | ○ |",
    ]) {
      assert.ok(lines.includes(line), `missing ${JSON.stringify(line)} in\n${lines.join("\n")}`);
    }
  } finally {
    s.stop();
  }
});

test("ROADMAP.md is the same text from two clones of the same plan", async () => {
  const s = await setup();
  try {
    await createTask(s.ctx, { title: "Another", project: "core", feature: "TST-FEAT1" });
    await s.sync().sync();
    const other = join(mkdtempSync(join(tmpdir(), "dashboard-roadmap-")), "clone");
    execFileSync("git", ["clone", "--quiet", s.f.remote, other], { stdio: "ignore" });
    assert.equal(renderRoadmap(loadPlan(other)), renderRoadmap(s.sync().plan));
  } finally {
    s.stop();
  }
});

test("the plugin's own commits carry ROADMAP.md as rendered from the plan they commit", async () => {
  const s = await setup();
  try {
    await updateTask(s.ctx, { task: "TST-FX001", title: "Fix the flaky login test" });
    const file = await s.remoteFile(/^ROADMAP\.md$/);
    assert.ok(file, "pushed with the change");
    assert.equal(file, renderRoadmap(s.sync().plan));
    assert.match(file!, /Fix the flaky login test/);
  } finally {
    s.stop();
  }
});

test("titles cannot break the table, the Markdown or the Mermaid labels", () => {
  const nasty = 'A "quoted" | piped [link](x) <b>#1</b> `code` *bold*\nnext';
  assert.equal(mdText(nasty), 'A "quoted" \\| piped \\[link\\](x) \\<b\\>\\#1\\</b\\> \\`code\\` \\*bold\\* next');
  assert.equal(mermaidLabel(nasty), "A #quot;quoted#quot; | piped [link](x) #lt;b#gt;#35;1#lt;/b#gt; #96;code#96; *bold* next");
  assert.equal(mdText("$x$ %%hidden%% ==mark=="), "\\$x\\$ \\%\\%hidden\\%\\% \\=\\=mark\\=\\=");
  // A directive anywhere in the diagram text would reconfigure it.
  assert.equal(mermaidLabel("%%{init: {'theme':'dark'}}%%"), "#37;#37;{init: {'theme':'dark'}}#37;#37;");
});

test("release titles that read as gantt keywords or dates, and dates that are not real, cannot break the gantt", async () => {
  const s = await setup();
  try {
    await createMilestone(s.ctx, { title: "Title page", due: "2026-12-01" });
    await createMilestone(s.ctx, { title: "2026-12-02 hotfix", due: "2026-12-02" });
    const text = renderRoadmap(s.sync().plan)!;
    assert.match(text, /^ {4}▸ Title page :milestone, r\d, 2026-12-01, 0d$/m);
    assert.match(text, /^ {4}▸ 2026-12-02 hotfix :milestone, r\d, 2026-12-02, 0d$/m);
  } finally {
    s.stop();
  }
});

test("a release's due date shows only when it is a real day", async () => {
  const s = await setup();
  try {
    s.f.external("anna", (root) => {
      writeFileSync(join(root, "milestones", "TST-MS002-odd.md"), '---\nid: TST-MS002\ntype: milestone\ntitle: Odd\nstatus: planned\ndue: "<details>"\n---\n');
      writeFileSync(join(root, "milestones", "TST-MS003-late.md"), "---\nid: TST-MS003\ntype: milestone\ntitle: Late\nstatus: planned\ndue: 2026-13-45\n---\n");
    });
    await s.sync().sync();
    const text = renderRoadmap(s.sync().plan)!;
    assert.doesNotMatch(text, /<details>|2026-13-45/);
    assert.match(text, /^## Odd · 0\/0 done$/m);
  } finally {
    s.stop();
  }
});

test("ROADMAP.md is the same text whatever the daemon's locale", () => {
  const root = mkdtempSync(join(tmpdir(), "dashboard-roadmap-locale-"));
  mkdirSync(join(root, "tasks"));
  mkdirSync(join(root, "features"));
  writeFileSync(join(root, "space.yaml"), "schema: paseo-dashboard/1\nkey: TST\nname: Locale\nprojects:\n  zz: { remote: git@x:zz.git }\n");
  writeFileSync(join(root, "features", "TST-FEAT0-f.md"), "---\nid: TST-FEAT0\ntype: feature\ntitle: F\nstatus: active\n---\n");
  for (const id of ["TST-ZAAAA", "TST-TAAAA", "TST-YAAAA", "TST-JAAAA"]) {
    writeFileSync(join(root, "tasks", `${id}-t.md`), `---\nid: ${id}\ntype: task\ntitle: ${id}\nstatus: todo\nproject: zz\nfeature: "[[TST-FEAT0-f]]"\n---\n`);
  }
  for (const project of ["aa-web", "zz-app"]) {
    writeFileSync(join(root, "tasks", `TST-${project === "aa-web" ? "A" : "B"}0000-p.md`), `---\nid: TST-${project === "aa-web" ? "A" : "B"}0000\ntype: task\ntitle: p\nstatus: todo\nproject: ${project}\n---\n`);
  }
  const script = `import { loadPlan } from ${JSON.stringify(new URL("./load.ts", import.meta.url).href)};
import { renderRoadmap } from ${JSON.stringify(new URL("./roadmap.ts", import.meta.url).href)};
process.stdout.write(renderRoadmap(loadPlan(${JSON.stringify(root)})));`;
  const render = (lang: string) =>
    execFileSync(process.execPath, ["--input-type=module", "-e", script], { env: { ...process.env, LANG: lang, LC_ALL: lang }, encoding: "utf8" });
  const here = renderRoadmap(loadPlan(root));
  for (const lang of ["et_EE.UTF-8", "lt_LT.UTF-8", "da_DK.UTF-8"]) assert.equal(render(lang), here, lang);
});

test("a ROADMAP.md that is not a plain file never stops a commit", async () => {
  const s = await setup();
  try {
    s.f.external("anna", (root) => symlinkSync("/etc/hosts", join(root, "ROADMAP.md")));
    await s.sync().sync();
    const changed = await updateTask(s.ctx, { task: "TST-FX001", title: "Still committed" });
    assert.equal(changed.ok, true, changed.error);
    await s.sync().sync();
    assert.equal(s.sync().state.pending, 0, "pushed");
    assert.equal(s.task("TST-FX001")!.title, "Still committed");
    assert.ok(s.sync().state.warnings.some((w) => /ROADMAP\.md was not updated/.test(w)));
  } finally {
    s.stop();
  }
});
